CREATE TABLE dim.dim_date (
    date_key INTEGER PRIMARY KEY,
    calendar_date DATE UNIQUE,
    year_no SMALLINT,
    quarter_no SMALLINT CHECK (quarter_no BETWEEN 1 AND 4),
    month_no SMALLINT CHECK (month_no BETWEEN 1 AND 12),
    day_no SMALLINT CHECK (day_no BETWEEN 1 AND 31),
    iso_weekday SMALLINT CHECK (iso_weekday BETWEEN 1 AND 7),
    CHECK ((date_key = 0 AND calendar_date IS NULL) OR
           (date_key <> 0 AND calendar_date IS NOT NULL AND
            date_key = EXTRACT(YEAR FROM calendar_date)::INTEGER * 10000
                     + EXTRACT(MONTH FROM calendar_date)::INTEGER * 100
                     + EXTRACT(DAY FROM calendar_date)::INTEGER))
);
