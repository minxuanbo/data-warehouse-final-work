-- 不直接连接多行商品明细和多行支付，先分别聚合为一行一单。
CREATE MATERIALIZED VIEW dws.order_wide AS
WITH item_sum AS (
    SELECT order_id, COUNT(*) AS item_count, SUM(price) AS item_amount,
           SUM(freight_value) AS freight_amount
    FROM dwd.fact_order_item GROUP BY order_id
), payment_sum AS (
    SELECT order_id, COUNT(*) AS payment_record_count,
           SUM(payment_value) AS payment_amount
    FROM dwd.fact_payment GROUP BY order_id
), base AS (
    SELECT o.*, i.item_count, i.item_amount, i.freight_amount,
           p.payment_record_count, p.payment_amount, r.review_score,
           (o.order_status = 'delivered') AS is_delivered,
           COALESCE(o.order_status = 'delivered'
             AND o.delivered_ts >= o.purchase_ts, FALSE) AS is_delivery_valid,
           COALESCE(o.order_status = 'delivered'
             AND o.delivered_ts >= o.purchase_ts
             AND o.estimated_ts::DATE >= o.purchase_ts::DATE, FALSE) AS is_late_valid
    FROM dwd.fact_order o
    LEFT JOIN item_sum i ON i.order_id = o.order_id
    LEFT JOIN payment_sum p ON p.order_id = o.order_id
    LEFT JOIN dwd.fact_review r ON r.order_id = o.order_id
)
SELECT b.*,
    CASE WHEN is_delivery_valid THEN EXTRACT(EPOCH FROM delivered_ts-purchase_ts)
         END AS delivery_seconds,
    CASE WHEN is_late_valid THEN delivered_ts::DATE > estimated_ts::DATE
         END AS is_late,
    CASE WHEN is_late_valid THEN GREATEST(delivered_ts::DATE-estimated_ts::DATE,0)
         END AS late_days
FROM base b WITH NO DATA;
CREATE UNIQUE INDEX idx_order_wide_id ON dws.order_wide(order_id);

CREATE VIEW dws.trade_day_geo AS
SELECT purchase_date_key, customer_geo_key,
       COUNT(*) AS all_order_count,
       COUNT(*) FILTER (WHERE is_delivered) AS delivered_order_count,
       SUM(item_amount) FILTER (WHERE is_delivered) AS item_amount,
       SUM(freight_amount) FILTER (WHERE is_delivered) AS freight_amount,
       SUM(payment_amount) FILTER (WHERE is_delivered) AS payment_amount,
       COUNT(*) FILTER (WHERE is_delivered AND item_count IS NULL) AS missing_item_orders,
       COUNT(*) FILTER (WHERE is_delivered AND payment_record_count IS NULL) AS missing_payment_orders
FROM dws.order_wide
GROUP BY purchase_date_key,customer_geo_key;

CREATE VIEW dws.fulfillment_day_geo AS
SELECT purchase_date_key, customer_geo_key,
       COUNT(*) FILTER (WHERE is_delivery_valid) AS valid_delivery_count,
       SUM(delivery_seconds) AS delivery_seconds_sum,
       COUNT(*) FILTER (WHERE is_late_valid) AS valid_late_count,
       COUNT(*) FILTER (WHERE is_late) AS late_order_count,
       SUM(late_days) FILTER (WHERE is_late) AS late_days_sum
FROM dws.order_wide
GROUP BY purchase_date_key,customer_geo_key;

CREATE VIEW dws.review_day_geo AS
SELECT purchase_date_key, customer_geo_key,
       COUNT(*) FILTER (WHERE is_delivered AND review_score IS NOT NULL) AS reviewed_order_count,
       SUM(review_score) FILTER (WHERE is_delivered) AS review_score_sum,
       COUNT(*) FILTER (WHERE is_delivered AND review_score IN (1,2)) AS low_score_order_count
FROM dws.order_wide
GROUP BY purchase_date_key,customer_geo_key;

-- 提供分子分母，Superset 跨日汇总时使用 SUM(分子)/NULLIF(SUM(分母),0)。
-- 不允许 AVG(日逾期率) 充当月逾期率。
CREATE VIEW ads.trade_overview AS
SELECT t.*, d.calendar_date, d.year_no, d.month_no, g.state_code,g.city_name,
       CASE WHEN missing_item_orders = 0
            THEN item_amount / NULLIF(delivered_order_count,0)
            END AS average_order_value
FROM dws.trade_day_geo t
JOIN dim.dim_date d ON d.date_key=t.purchase_date_key
JOIN dim.dim_geography g ON g.geo_key=t.customer_geo_key;
CREATE VIEW ads.fulfillment_overview AS
SELECT f.*, d.calendar_date, d.year_no, d.month_no, g.state_code,g.city_name,
       delivery_seconds_sum / NULLIF(valid_delivery_count,0) / 86400.0 AS average_delivery_days,
       late_order_count::NUMERIC / NULLIF(valid_late_count,0) AS late_rate,
       late_days_sum::NUMERIC / NULLIF(late_order_count,0) AS average_late_days
FROM dws.fulfillment_day_geo f
JOIN dim.dim_date d ON d.date_key=f.purchase_date_key
JOIN dim.dim_geography g ON g.geo_key=f.customer_geo_key;
CREATE VIEW ads.review_overview AS
SELECT r.*, d.calendar_date, d.year_no, d.month_no, g.state_code,g.city_name,
       review_score_sum::NUMERIC / NULLIF(reviewed_order_count,0) AS average_review_score,
       low_score_order_count::NUMERIC / NULLIF(reviewed_order_count,0) AS low_score_rate
FROM dws.review_day_geo r
JOIN dim.dim_date d ON d.date_key=r.purchase_date_key
JOIN dim.dim_geography g ON g.geo_key=r.customer_geo_key;

COMMENT ON MATERIALIZED VIEW dws.order_wide IS '每订单一行；分别聚合商品明细和支付；缺失金额保留NULL；ETL事务内刷新';
COMMENT ON TABLE dwd.fact_review IS '每订单一条代表评价；先按回复时间、创建时间、评价ID、源行号降序选择，再验证评分';
COMMENT ON COLUMN dwd.fact_payment.purchase_date_key IS '订单下单日期；源支付文件没有实际支付时间';
COMMENT ON VIEW ads.trade_overview IS '金额发布前检查 missing_item_orders 和 missing_payment_orders；不可静默忽略缺失金额';
COMMIT;
