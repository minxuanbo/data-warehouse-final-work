CREATE TABLE audit.load_batch (
    batch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at TIMESTAMPTZ,
    status TEXT NOT NULL CHECK (status IN ('running','passed','failed')),
    code_version TEXT,
    error_message TEXT
);
CREATE TABLE audit.source_file (
    batch_id BIGINT NOT NULL REFERENCES audit.load_batch,
    file_name TEXT NOT NULL,
    source_url TEXT NOT NULL,
    sha256 VARCHAR(64) NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    row_count BIGINT NOT NULL CHECK (row_count >= 0),
    downloaded_at TIMESTAMPTZ,
    license_note TEXT,
    PRIMARY KEY (batch_id, file_name)
);
CREATE TABLE audit.quality_result (
    check_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL REFERENCES audit.load_batch,
    model_name TEXT NOT NULL,
    check_name TEXT NOT NULL,
    severity TEXT NOT NULL CHECK (severity IN ('error','warning')),
    passed BOOLEAN NOT NULL,
    failed_count BIGINT NOT NULL CHECK (failed_count >= 0),
    details TEXT,
    checked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE audit.rejected_record (
    reject_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL REFERENCES audit.load_batch,
    file_name TEXT NOT NULL,
