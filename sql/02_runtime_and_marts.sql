CREATE VIEW dws.trade_day_category AS
SELECT i.purchase_date_key,p.category_name,
       SUM(i.price) AS item_amount,SUM(i.freight_value) AS freight_amount,
       COUNT(*) AS item_count,COUNT(DISTINCT i.order_id) AS order_count
FROM dwd.fact_order_item i
JOIN dwd.fact_order o USING(order_id)
JOIN dim.dim_product p USING(product_key)
WHERE o.order_status='delivered'
GROUP BY i.purchase_date_key,p.category_name;
CREATE VIEW dws.trade_day_seller AS
SELECT i.purchase_date_key,i.seller_key,
       SUM(i.price) AS item_amount,SUM(i.freight_value) AS freight_amount,
       COUNT(*) AS item_count,COUNT(DISTINCT i.order_id) AS order_count
FROM dwd.fact_order_item i JOIN dwd.fact_order o USING(order_id)
WHERE o.order_status='delivered'
GROUP BY i.purchase_date_key,i.seller_key;
CREATE VIEW dws.delivery_review_group AS
SELECT purchase_date_key,customer_geo_key,is_late,
       COUNT(*) AS reviewed_orders,SUM(review_score) AS score_sum,
       COUNT(*) FILTER (WHERE review_score IN (1,2)) AS low_score_orders
FROM dws.order_wide WHERE is_late_valid AND review_score IS NOT NULL
GROUP BY purchase_date_key,customer_geo_key,is_late;

-- Existing daily interface keeps payment_amount as recorded source sum.
-- New public KPI interfaces name recorded vs complete payment explicitly.
CREATE VIEW ads.kpi_overview AS
SELECT COUNT(*) AS all_orders,
 COUNT(*) FILTER (WHERE is_delivered) AS delivered_orders,
 SUM(item_amount) FILTER (WHERE is_delivered) AS item_amount,
 SUM(freight_amount) FILTER (WHERE is_delivered) AS freight_amount,
 SUM(payment_amount) FILTER (WHERE is_delivered) AS recorded_payment_amount,
 COUNT(*) FILTER (WHERE is_delivered AND payment_record_count IS NULL) AS missing_payment_orders,
 CASE WHEN COUNT(*) FILTER (WHERE is_delivered AND payment_record_count IS NULL)=0
      THEN SUM(payment_amount) FILTER (WHERE is_delivered) END AS complete_payment_amount,
 COUNT(*) FILTER (WHERE is_delivered AND payment_record_count IS NOT NULL)::NUMERIC
   / NULLIF(COUNT(*) FILTER (WHERE is_delivered),0) AS payment_order_coverage,
 CASE WHEN COUNT(*) FILTER (WHERE is_delivered AND item_count IS NULL)=0
      THEN SUM(item_amount) FILTER (WHERE is_delivered)
           /NULLIF(COUNT(*) FILTER (WHERE is_delivered),0) END AS average_order_value,
 COUNT(DISTINCT c.customer_unique_id) FILTER (WHERE is_delivered) AS delivered_buyers,
 COUNT(*) FILTER (WHERE is_delivery_valid) AS valid_delivery_orders,
 SUM(delivery_seconds)/NULLIF(COUNT(*) FILTER (WHERE is_delivery_valid),0)/86400.0 AS average_delivery_days,
 COUNT(*) FILTER (WHERE is_late_valid) AS late_eligible_orders,
 COUNT(*) FILTER (WHERE is_late) AS late_orders,
 COUNT(*) FILTER (WHERE is_late)::NUMERIC/NULLIF(COUNT(*) FILTER (WHERE is_late_valid),0) AS late_rate,
 COUNT(*) FILTER (WHERE is_delivered AND review_score IS NOT NULL) AS reviewed_orders,
 AVG(review_score) FILTER (WHERE is_delivered) AS average_review_score,
 COUNT(*) FILTER (WHERE is_delivered AND review_score IN (1,2)) AS low_score_orders,
 COUNT(*) FILTER (WHERE is_delivered AND review_score IN (1,2))::NUMERIC
 /NULLIF(COUNT(*) FILTER (WHERE is_delivered AND review_score IS NOT NULL),0) AS low_score_rate
FROM dws.order_wide w JOIN dim.dim_customer c USING(customer_key);

CREATE VIEW ads.trade_month AS
SELECT d.year_no,d.month_no,
 SUM(all_order_count) AS all_orders,SUM(delivered_order_count) AS delivered_orders,
 SUM(item_amount) AS item_amount,SUM(freight_amount) AS freight_amount,
 SUM(payment_amount) AS recorded_payment_amount,SUM(missing_payment_orders) AS missing_payment_orders,
 CASE WHEN SUM(missing_payment_orders)=0 THEN SUM(payment_amount) END AS complete_payment_amount,
 CASE WHEN SUM(missing_item_orders)=0 THEN SUM(item_amount)/NULLIF(SUM(delivered_order_count),0) END AS average_order_value
FROM dws.trade_day_geo t JOIN dim.dim_date d ON d.date_key=t.purchase_date_key
GROUP BY d.year_no,d.month_no;
CREATE VIEW ads.fulfillment_state AS
SELECT g.state_code,SUM(valid_delivery_count) AS valid_delivery_orders,
 SUM(delivery_seconds_sum)/NULLIF(SUM(valid_delivery_count),0)/86400.0 AS average_delivery_days,
 SUM(valid_late_count) AS late_eligible_orders,SUM(late_order_count) AS late_orders,
 SUM(late_order_count)::NUMERIC/NULLIF(SUM(valid_late_count),0) AS late_rate
FROM dws.fulfillment_day_geo f JOIN dim.dim_geography g ON g.geo_key=f.customer_geo_key
GROUP BY g.state_code;
CREATE VIEW ads.category_ranking AS
SELECT category_name,SUM(item_amount) AS item_amount,SUM(item_count) AS item_count,
 SUM(order_count) AS category_order_count
FROM dws.trade_day_category GROUP BY category_name;
CREATE VIEW ads.seller_ranking AS
SELECT s.seller_id,SUM(t.item_amount) AS item_amount,SUM(t.item_count) AS item_count,
 SUM(t.order_count) AS seller_order_count
FROM dws.trade_day_seller t JOIN dim.dim_seller s USING(seller_key) GROUP BY s.seller_id;
CREATE VIEW ads.delivery_review_comparison AS
SELECT is_late,SUM(reviewed_orders) AS reviewed_orders,
 SUM(score_sum)::NUMERIC/NULLIF(SUM(reviewed_orders),0) AS average_score,
 SUM(low_score_orders) AS low_score_orders,
 SUM(low_score_orders)::NUMERIC/NULLIF(SUM(reviewed_orders),0) AS low_score_rate
FROM dws.delivery_review_group GROUP BY is_late;
CREATE VIEW ads.review_distribution AS
SELECT review_score,COUNT(*) AS reviewed_orders FROM dws.order_wide
WHERE is_delivered AND review_score IS NOT NULL GROUP BY review_score;
CREATE VIEW ads.payment_quality AS
SELECT order_id,order_status,item_amount,freight_amount,payment_amount AS recorded_payment_amount,
 payment_record_count IS NULL AS payment_missing,
 payment_amount-item_amount-freight_amount AS recorded_difference
FROM dws.order_wide
WHERE payment_record_count IS NULL OR payment_amount<>item_amount+freight_amount;

